/**
 * Semantic acceptance for Access consumer answers (issue #301).
 *
 * Extraction tests prove the graph holds what it should. This layer proves the
 * ANSWERS are right: which expected paths and entities are missing, and which
 * unrelated ones are reported. Both directions matter — a consumer that
 * answers for the wrong form is as broken as one that answers nothing, and
 * node/edge counts detect neither.
 *
 * It reuses this evaluation harness rather than starting a parallel runner,
 * and it queries the same PUBLIC surfaces a consumer uses
 * (`CodeGraph.getBehaviorEvidence`, `runImpactAnalysis`) over a FRESH,
 * isolated index built by production extraction and resolution. Expected
 * answers come from `vba-consumer-semantics-ground-truth.json`, read off the
 * source by hand; nothing here is generated by the code under evaluation.
 *
 * Passing this corpus is not certification of arbitrary projects, and it says
 * nothing about live Access execution.
 */
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { CodeGraph, DatabaseConnection, getDatabasePath } from '../../src';
import { runImpactAnalysis } from '../../src/utils/sql-impact-helpers';

const CHECKED_IN_CORPUS_DIR = path.join(
  __dirname,
  '..',
  'fixtures',
  'vba-consumer-semantics',
);
const CHECKED_IN_GROUND_TRUTH_PATH = path.join(
  __dirname,
  '..',
  'fixtures',
  'vba-consumer-semantics-ground-truth.json',
);

/**
 * Opt-in local evaluation. Set both to point the SAME criteria and harness at
 * an authorized copy of a real export plus your own ground-truth file:
 *
 *   VBA_ACCEPTANCE_CORPUS=/path/to/export-copy
 *   VBA_ACCEPTANCE_GROUND_TRUTH=/path/to/ground-truth.json
 *   npm run acceptance:vba
 *
 * The run is local and reads only the directory you name. Nothing is
 * uploaded, no `.accdb` is touched, no project is discovered on your machine,
 * and no local path is retained in this repository — which is also why these
 * are environment variables rather than a checked-in setting. Keep a
 * ground-truth file derived from private data beside the export copy; do not
 * commit it.
 */
export const DEFAULT_CORPUS_DIR =
  process.env.VBA_ACCEPTANCE_CORPUS || CHECKED_IN_CORPUS_DIR;
export const DEFAULT_GROUND_TRUTH_PATH =
  process.env.VBA_ACCEPTANCE_GROUND_TRUTH || CHECKED_IN_GROUND_TRUTH_PATH;

/** True when the run was pointed at a local export instead of the fixture. */
export const USING_LOCAL_CORPUS =
  DEFAULT_CORPUS_DIR !== CHECKED_IN_CORPUS_DIR ||
  DEFAULT_GROUND_TRUTH_PATH !== CHECKED_IN_GROUND_TRUTH_PATH;

export type AcceptanceCaseKind = 'behavior' | 'ambiguity' | 'impact' | 'layout';

/**
 * The normalized facts one case's answer can contain. Every ground-truth
 * expectation and rejection is expressed against these keys, so the comparison
 * is one generic set operation instead of a rule per case.
 */
export interface AcceptanceAnswer {
  handlers: string[];
  /** Root-to-leaf paths, each serialized for comparison by the evaluator. */
  callPaths: string[][];
  /** Every procedure named on any path — what a `reject` rule is checked against. */
  callPathMembers: string[];
  tables: string[];
  effects: string[];
  scopes: string[];
  unresolved: string[];
  notes: string[];
  ambiguousLayouts: string[];
  forms: string[];
  vbaCallers: string[];
  formBindings: string[];
  kinds: string[];
}

export interface AcceptanceCase {
  id: string;
  kind: AcceptanceCaseKind;
  question: string;
  source: string;
  target: Record<string, unknown>;
  expect?: Partial<Record<keyof AcceptanceAnswer, unknown>>;
  reject?: Partial<Record<keyof AcceptanceAnswer, unknown>>;
}

export interface GroundTruth {
  corpus: string;
  cases: AcceptanceCase[];
}

export interface AcceptanceCaseResult {
  id: string;
  kind: AcceptanceCaseKind;
  question: string;
  source: string;
  status: 'passed' | 'failed';
  /** Expected identities or relationships the answer did not contain. */
  missing: string[];
  /** Identities or relationships the answer contained but must not have. */
  unexpected: string[];
}

export interface AcceptanceReport {
  passed: number;
  failed: number;
  cases: AcceptanceCaseResult[];
  /**
   * Reproduction metadata. Deliberately NOT part of any comparison: it carries
   * versions and the repo-relative corpus path, never a timestamp and never
   * the temporary directory the throwaway index was built in.
   */
  environment: {
    node: string;
    package: string;
    corpus: string;
    groundTruth: string;
    caseCount: number;
    index: string;
  };
}

export interface AcceptanceOptions {
  /** Defaults to the checked-in corpus. Point it at an authorized local export copy to evaluate that instead. */
  corpusDir?: string;
  groundTruthPath?: string;
  /**
   * Test hook. Lets a test feed the comparison a deliberately wrong answer —
   * a cross-form path, a dropped step — to prove the evaluator catches it.
   * Never used by the real run.
   */
  perturb?: (id: string, answer: AcceptanceAnswer) => AcceptanceAnswer;
}

function emptyAnswer(): AcceptanceAnswer {
  return {
    handlers: [],
    callPaths: [],
    callPathMembers: [],
    tables: [],
    effects: [],
    scopes: [],
    unresolved: [],
    notes: [],
    ambiguousLayouts: [],
    forms: [],
    vbaCallers: [],
    formBindings: [],
    kinds: [],
  };
}

/** Serialize a value so a path (`string[]`) and a name compare the same way. */
function token(value: unknown): string {
  return Array.isArray(value) ? value.join(' -> ') : String(value);
}

function tokensOf(answer: AcceptanceAnswer, key: keyof AcceptanceAnswer): Set<string> {
  return new Set((answer[key] as unknown[]).map(token));
}

function compare(
  testCase: AcceptanceCase,
  answer: AcceptanceAnswer,
): AcceptanceCaseResult {
  const missing: string[] = [];
  const unexpected: string[] = [];

  for (const [key, wanted] of Object.entries(testCase.expect ?? {})) {
    const present = tokensOf(answer, key as keyof AcceptanceAnswer);
    const wantedList = (wanted as unknown[]).map(token);
    for (const item of wantedList) {
      if (!present.has(item)) missing.push(`${key}: ${item}`);
    }
    // An expectation of NOTHING is a real expectation: `tables: []` asserts the
    // answer reports no table, not that the key was left unchecked.
    if (wantedList.length === 0) {
      for (const item of present) unexpected.push(`${key}: ${item}`);
    }
  }

  for (const [key, forbidden] of Object.entries(testCase.reject ?? {})) {
    const present = tokensOf(answer, key as keyof AcceptanceAnswer);
    for (const item of (forbidden as unknown[]).map(token)) {
      if (present.has(item)) unexpected.push(`${key}: ${item}`);
    }
  }

  return {
    id: testCase.id,
    kind: testCase.kind,
    question: testCase.question,
    source: testCase.source,
    status: missing.length === 0 && unexpected.length === 0 ? 'passed' : 'failed',
    missing: missing.sort(),
    unexpected: unexpected.sort(),
  };
}

/**
 * Build the answer for one case by asking the same public surfaces a consumer
 * would ask. No case reads private state, and none inserts an edge.
 */
function answerFor(
  testCase: AcceptanceCase,
  cg: CodeGraph,
  dir: string,
  db: ReturnType<DatabaseConnection['getDb']>,
): AcceptanceAnswer {
  const answer = emptyAnswer();

  if (testCase.kind === 'behavior' || testCase.kind === 'ambiguity') {
    const evidence = cg.getBehaviorEvidence(
      testCase.target as { name?: string; layout?: string },
    );
    answer.notes = evidence.context.notes;
    answer.handlers = [...new Set(evidence.context.handlers.map((h) => h.handler))];
    answer.scopes = [...new Set(evidence.context.handlers.map((h) => h.scope))];
    answer.callPaths = evidence.evidence.map((entry) => entry.callPath);
    answer.callPathMembers = [
      ...new Set(evidence.evidence.flatMap((entry) => entry.callPath)),
    ];
    answer.tables = [...new Set(evidence.evidence.flatMap((entry) => entry.tables ?? []))];
    answer.effects = [
      ...new Set(evidence.evidence.flatMap((entry) => entry.effects ?? [])),
    ];
    answer.unresolved = [
      ...new Set(evidence.context.unresolved.map((u) => u.referenceName)),
    ];
    answer.ambiguousLayouts = [
      ...new Set(
        evidence.context.ambiguous.flatMap((a) =>
          a.matches.map((m) => m.layout ?? m.filePath),
        ),
      ),
    ].sort();
    return answer;
  }

  if (testCase.kind === 'impact') {
    const impact = runImpactAnalysis(db, dir, String(testCase.target.query));
    answer.forms = impact.downstream_impact.forms;
    answer.vbaCallers = impact.downstream_impact.vba_callers;
    answer.formBindings = impact.form_bindings.map(
      (b: { control: string; property: string; target: string }) =>
        `${b.control}.${b.property}=${b.target}`,
    );
    return answer;
  }

  // layout: what the layout files themselves emit.
  const files = testCase.target.files as string[];
  const kinds = new Set<string>();
  for (const file of files) {
    for (const row of db
      .prepare('SELECT DISTINCT kind FROM nodes WHERE file_path = ?')
      .all(file) as Array<{ kind: string }>) {
      kinds.add(row.kind);
    }
  }
  answer.kinds = [...kinds].sort();
  return answer;
}

/**
 * Index a throwaway copy of the corpus and evaluate every ground-truth case
 * against it. The copy is deleted before returning, so nothing is left behind
 * and no state carries between runs.
 */
export async function runSemanticAcceptance(
  options: AcceptanceOptions = {},
): Promise<AcceptanceReport> {
  const corpusDir = options.corpusDir ?? DEFAULT_CORPUS_DIR;
  const groundTruthPath = options.groundTruthPath ?? DEFAULT_GROUND_TRUTH_PATH;
  const groundTruth = JSON.parse(
    fs.readFileSync(groundTruthPath, 'utf-8'),
  ) as GroundTruth;

  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'vba-semantic-acceptance-'));
  const pkg = JSON.parse(
    fs.readFileSync(path.join(__dirname, '..', '..', 'package.json'), 'utf-8'),
  ) as { name: string; version: string };

  fs.cpSync(corpusDir, dir, { recursive: true });

  let cases: AcceptanceCaseResult[];
  const cg = await CodeGraph.init(dir, { index: false });
  try {
    await cg.indexAll();
    const conn = DatabaseConnection.open(getDatabasePath(dir));
    try {
      cases = groundTruth.cases.map((testCase) => {
        const raw = answerFor(testCase, cg, dir, conn.getDb());
        const answer = options.perturb ? options.perturb(testCase.id, raw) : raw;
        return compare(testCase, answer);
      });
    } finally {
      conn.close();
    }
  } finally {
    await cg.close();
    fs.rmSync(dir, { recursive: true, force: true });
  }

  const repoRoot = path.join(__dirname, '..', '..');
  const local =
    corpusDir !== CHECKED_IN_CORPUS_DIR ||
    groundTruthPath !== CHECKED_IN_GROUND_TRUTH_PATH;

  return {
    passed: cases.filter((c) => c.status === 'passed').length,
    failed: cases.filter((c) => c.status === 'failed').length,
    cases,
    environment: {
      node: process.version,
      package: `${pkg.name}@${pkg.version}`,
      // A local export copy is reported WITHOUT its path: the report is meant
      // to be pasteable into an issue, and a private path is not evidence.
      corpus: local
        ? 'local export copy (path not recorded)'
        : path.relative(repoRoot, corpusDir).split(path.sep).join('/'),
      groundTruth: local
        ? 'local ground truth (path not recorded)'
        : path.relative(repoRoot, groundTruthPath).split(path.sep).join('/'),
      caseCount: groundTruth.cases.length,
      index: 'fresh throwaway copy, indexAll() with default settings, deleted after the run',
    },
  };
}

/** Human-readable report. Deterministic — no timings, no temporary paths. */
export function formatAcceptanceReport(report: AcceptanceReport): string {
  const lines: string[] = [
    'VBA semantic acceptance',
    `  corpus:       ${report.environment.corpus}`,
    `  ground truth: ${report.environment.groundTruth}`,
    `  node:         ${report.environment.node}`,
    `  package:      ${report.environment.package}`,
    `  index:        ${report.environment.index}`,
    '',
  ];
  for (const result of report.cases) {
    lines.push(
      `${result.status === 'passed' ? 'PASS' : 'FAIL'}  ${result.id}  [${result.kind}]`,
    );
    lines.push(`      ${result.question}`);
    lines.push(`      source: ${result.source}`);
    for (const item of result.missing) lines.push(`      MISSING    ${item}`);
    for (const item of result.unexpected) lines.push(`      UNEXPECTED ${item}`);
  }
  lines.push('', `${report.passed} passed, ${report.failed} failed`);
  return lines.join('\n');
}
